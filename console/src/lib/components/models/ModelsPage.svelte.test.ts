test('scorecard: header clicks sort, labels follow the name switch', async () => {
	const onSort = vi.fn();
	render(BehaviourScorecard, {
		rates: data.rates,
		rows: data.scorecard,
		selected: null,
		metric: null,
		sort: 'group',
		dir: 'desc',
		labelOf: (g: string) => data.models?.[g]?.id ?? g,
		onSelect: () => {},
		onSort
	});
	const groups = page.getByTestId('scorecard-group');
	await expect.element(groups.first()).toHaveTextContent('vendor/model-b');
	await expect.element(groups.nth(2)).toHaveTextContent('vendor/cap-model');
	await page.getByTestId('sort-nudged_per_session').click();
	expect(onSort).toHaveBeenCalledWith('nudged_per_session');
	await page.getByTestId('sort-volume').click();
	expect(onSort).toHaveBeenCalledWith('volume');
});

